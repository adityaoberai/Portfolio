import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { sep } from 'node:path';
import { site } from '../src/lib/data/site.ts';

const args = process.argv.slice(2);
if (args.some((arg) => arg !== '--check'))
	throw new Error('Usage: node scripts/sitemap.mjs [--check]');

// Redirect-only routes have no +page.svelte file. The noindex fallback is the
// only content page deliberately excluded; the browser check verifies its policy.
const excluded = new Set(['/404']);
const pages = readdirSync(new URL('../src/routes/', import.meta.url), {
	recursive: true,
	encoding: 'utf8'
})
	.map((file) => file.split(sep).join('/'))
	.filter((file) => file === '+page.svelte' || file.endsWith('/+page.svelte'))
	.map((file) => {
		const segments = file
			.split('/')
			.slice(0, -1)
			.filter((part) => !/^\(.*\)$/.test(part));
		if (segments.some((part) => part.includes('[')))
			throw new Error(`Add concrete sitemap URLs for the parameterized route ${file}`);
		return `/${segments.join('/')}`;
	})
	.filter((path) => !excluded.has(path))
	.sort();

if (new Set(pages).size !== pages.length)
	throw new Error('Duplicate page paths in sitemap discovery');
const escapeXml = (value) =>
	value.replace(
		/[<>&"']/g,
		(character) =>
			({
				'<': '&lt;',
				'>': '&gt;',
				'&': '&amp;',
				'"': '&quot;',
				"'": '&apos;'
			})[character]
	);
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by npm run sitemap:update. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((path) => `\t<url><loc>${escapeXml(new URL(path, site.url).href)}</loc></url>`).join('\n')}
</urlset>
`;
const output = new URL('../static/sitemap.xml', import.meta.url);
const current = existsSync(output) ? readFileSync(output, 'utf8') : null;

if (args.includes('--check')) {
	if (current !== xml) {
		console.error(
			'Sitemap is missing or stale. Run npm run sitemap:update and commit static/sitemap.xml.'
		);
		process.exitCode = 1;
	} else console.log(`Sitemap is current: ${pages.length} public pages.`);
} else if (current !== xml) {
	writeFileSync(output, xml);
	console.log(`Updated static/sitemap.xml: ${pages.length} public pages.`);
} else console.log(`Sitemap is current: ${pages.length} public pages.`);
